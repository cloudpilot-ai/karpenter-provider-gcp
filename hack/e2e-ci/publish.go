func RunURL(f Frozen) string {
	return fmt.Sprintf("https://github.com/%s/actions/runs/%d", Repository, f.Dispatch.RunID)
}
func checkName(f Frozen) string { return "Manual e2e / " + f.Dispatch.Preset }
func externalID(f Frozen) string {
	return fmt.Sprintf("e2e:%d:1:%s:pr:%d", f.Dispatch.RunID, f.Dispatch.Preset, f.PRNumber)
}

func (g Gate) write(ctx context.Context, method, path string, value, dest any) error {
	data, err := json.Marshal(value)
	if err != nil {
		return err
	}
	base := g.APIURL
	if base == "" {
		base = "https://api.github.com"
	}
	req, err := http.NewRequestWithContext(ctx, method, base+path, bytes.NewReader(data))
	if err != nil {
		return err
	}
	req.Header.Set("Authorization", "Bearer "+g.Token)
	req.Header.Set("Accept", "application/vnd.github+json")
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("X-GitHub-Api-Version", "2022-11-28")
	client := g.Client
	if client == nil {
		client = http.DefaultClient
	}
	c := *client
	c.CheckRedirect = func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }
	res, err := c.Do(req)
	if err != nil {
		return err
	}
	defer res.Body.Close()
	if res.StatusCode < 200 || res.StatusCode >= 300 {
		return fmt.Errorf("GitHub publication %s returned %d", path, res.StatusCode)
	}
	data, err = io.ReadAll(io.LimitReader(res.Body, (1<<20)+1))
	if err != nil {
		return err
	}
	if len(data) > 1<<20 {
		return errors.New("publication response too large")
	}
	if dest != nil {
		return json.Unmarshal(data, dest)
	}
	return nil
}

func (g Gate) Pending(ctx context.Context, f Frozen) (int64, error) {
	if err := f.Validate(); err != nil {
		return 0, err
	}
	var check struct {
		ID int64 `json:"id"`
	}
	err := g.write(ctx, http.MethodPost, "/repos/"+Repository+"/check-runs", map[string]any{"name": checkName(f), "head_sha": f.HeadSHA, "external_id": externalID(f), "status": "in_progress", "details_url": RunURL(f), "output": map[string]string{"title": "Captured " + f.HeadSHA, "summary": "Maintainer-dispatched " + f.Dispatch.Preset + "; awaiting build/runtime evidence. Missing evidence cannot pass."}}, &check)
	if err == nil && check.ID <= 0 {
		err = errors.New("missing check ID")
	}
	return check.ID, err
}

// Delivery is persisted independently from test evidence. A failed check update
// does not prevent the comment attempt, nor does either failure become success.
type Delivery struct {
	Check   string `json:"check"`
	Comment string `json:"comment"`
}

func commentMarker(f Frozen) string {
	return fmt.Sprintf("<!-- karpenter-e2e:%s run=%d sha=%s -->", f.Dispatch.Preset, f.Dispatch.RunID, f.HeadSHA)
}

type resultComment struct {
	ID   int64  `json:"id"`
	Body string `json:"body"`
	User struct {
		Login string `json:"login"`
		Type  string `json:"type"`
	} `json:"user"`
}

func (g Gate) resultComments(ctx context.Context, f Frozen) ([]resultComment, error) {
	var all []resultComment
	for page := 1; page <= 10; page++ {
		var comments []resultComment
		if err := g.get(ctx, fmt.Sprintf("/repos/%s/issues/%d/comments?per_page=100&page=%d", Repository, f.PRNumber, page), &comments); err != nil {
			return nil, err
		}
		all = append(all, comments...)
		if len(comments) < 100 {
			return all, nil
		}
	}
	return nil, errors.New("too many comments; manual reconciliation required")
}

// Publish must run under the workflow's per-PR/preset publication concurrency.
// Ordering is read while holding that lock; GitHub's pending-job order is not FIFO.
// Markdown must be generated by the trusted offline renderer, never downloaded.
func (g Gate) Publish(ctx context.Context, f Frozen, id int64, conclusion, markdown string) Delivery {
	result := Delivery{Check: "failed", Comment: "failed"}
	if f.Validate() != nil || id <= 0 || len(markdown) > 60000 || strings.Contains(markdown, "\x00") {
		return result
	}
	switch conclusion {
	case "success", "failure", "cancelled":
	default:
		return result
	}
	var check struct {
		ID         int64  `json:"id"`
		HeadSHA    string `json:"head_sha"`
		ExternalID string `json:"external_id"`
		App        struct {
			Slug string `json:"slug"`
		} `json:"app"`
	}
	checkPath := fmt.Sprintf("/repos/%s/check-runs/%d", Repository, id)
	if g.get(ctx, checkPath, &check) != nil || check.ID != id || check.HeadSHA != f.HeadSHA || check.ExternalID != externalID(f) || check.App.Slug != "github-actions" {
		return result
	}
	summary := fmt.Sprintf("%s\n\nSource: `%s` · tooling: `%s` · actor: `%s` (%d)\n\n[Invocation](%s)\n\n%s", commentMarker(f), f.HeadSHA, f.Dispatch.WorkflowSHA, f.Dispatch.Actor, f.Dispatch.ActorID, RunURL(f), markdown)
	if len(summary) > 65000 {
		return result
	}
	// The invocation-specific check is independent of shared-comment ordering.
	if g.write(ctx, http.MethodPatch, checkPath, map[string]any{"status": "completed", "conclusion": conclusion, "output": map[string]string{"title": checkName(f) + " / " + conclusion, "summary": summary}}, nil) == nil {
		result.Check = "passed"
	}
	comments, err := g.resultComments(ctx, f)
	if err != nil {
		return result
	}
	marker := regexp.MustCompile(`^<!-- karpenter-e2e:` + regexp.QuoteMeta(f.Dispatch.Preset) + ` run=([1-9][0-9]*) sha=[a-f0-9]{40} -->\n`)
	var updateID, newestRun int64
	superseded, err := g.newerCheck(ctx, f)
	if err != nil {
		return result
	}
	for _, comment := range comments {
		if comment.User.Type != "Bot" || comment.User.Login != "github-actions[bot]" {
			continue
		}
		match := marker.FindStringSubmatch(comment.Body + "\n")
		if match == nil {
			continue
		}
		run, err := strconv.ParseInt(match[1], 10, 64)
		if err != nil {
			return result
		}
		if run > f.Dispatch.RunID {
			superseded = true
		}
		if run > newestRun || run == newestRun && comment.ID > updateID {
			newestRun, updateID = run, comment.ID
		}
	}
	if superseded {
		result.Comment = "superseded"
		return result
	}
	var pr pullRequest
	if g.get(ctx, fmt.Sprintf("/repos/%s/pulls/%d", Repository, f.PRNumber), &pr) != nil {
		return result
	}
	if pr.Head.SHA != f.HeadSHA {
		result.Comment = "stale-sha"
		return result
	}
	path := fmt.Sprintf("/repos/%s/issues/%d/comments", Repository, f.PRNumber)
	method := http.MethodPost
	if updateID > 0 {
		path = fmt.Sprintf("/repos/%s/issues/comments/%d", Repository, updateID)
		method = http.MethodPatch
	}
	if g.write(ctx, method, path, map[string]string{"body": summary}, nil) == nil {
		result.Comment = "passed"
	}
	return result
}

func (g Gate) newerCheck(ctx context.Context, f Frozen) (bool, error) {
	pattern := regexp.MustCompile(`^e2e:([1-9][0-9]*):1:` + regexp.QuoteMeta(f.Dispatch.Preset) + `:pr:` + strconv.FormatInt(f.PRNumber, 10) + `$`)
	for page := 1; page <= 10; page++ {
		var list struct {
			Checks []struct {
				HeadSHA    string `json:"head_sha"`
				ExternalID string `json:"external_id"`
				App        struct {
					Slug string `json:"slug"`
				} `json:"app"`
			} `json:"check_runs"`
		}
		path := fmt.Sprintf("/repos/%s/commits/%s/check-runs?check_name=%s&filter=all&per_page=100&page=%d", Repository, f.HeadSHA, url.QueryEscape(checkName(f)), page)
		if err := g.get(ctx, path, &list); err != nil {
			return false, err
		}
		for _, check := range list.Checks {
			if check.App.Slug != "github-actions" || check.HeadSHA != f.HeadSHA {
				continue
			}
			m := pattern.FindStringSubmatch(check.ExternalID)
			if m == nil {
				continue
			}
			run, err := strconv.ParseInt(m[1], 10, 64)
			if err != nil {
				return false, err
			}
			if run > f.Dispatch.RunID {
				return true, nil
			}
		}
		if len(list.Checks) < 100 {
			return false, nil
		}
	}
	return false, errors.New("too many checks; reconcile manually")
}
